/**
 * GitHub API Client
 * Hybrid approach: Tries cached data first, falls back to API if needed
 */

import { validateGitHubUsername, validateRepoFormat } from './validators';

/**
 * API Base URL - Points to the backend server
 */
const API_BASE = import.meta.env.VITE_API_BASE_URL || 'https://jagdnotionapiserver.vercel.app/api';

export interface GitHubContribution {
  date: string;
  count: number;
}

export interface GitHubContributionCalendar {
  totalContributions: number;
  weeks: Array<{
    contributionDays: GitHubContribution[];
  }>;
}

export interface GitHubCommit {
  id: string;
  date: string;
  week: string;
  type: 'feature' | 'fix' | 'design' | 'infra';
  content: string;
  assignee: string;
  assigneeImg?: string;
}

interface TeamMemberStats {
  name: string;
  github: {
    username: string;
    contributions: GitHubContribution[];
  };
  leetcode: {
    username: string;
    stats: {
      totalSolved: number;
      easySolved: number;
      mediumSolved: number;
      hardSolved: number;
      recentSubmissions: Array<{ date: string; count: number }>;
    };
  } | null;
}

// Cache for static data
let teamStatsCache: TeamMemberStats[] | null = null;
let cacheAttempted = false;

/**
 * Try to load from static cache (generated by sync script)
 */
async function tryLoadCache(): Promise<TeamMemberStats[]> {
  if (!cacheAttempted) {
    cacheAttempted = true;
    try {
      // Use dynamic import with template to prevent Vite static analysis
      const modulePath = `@/data/${'teamStats'}`;
      const module = await import(/* @vite-ignore */ modulePath);
      teamStatsCache = module.teamStats;
      if (import.meta.env.DEV) {
        console.log('✅ Loaded cached team stats from static file');
      }
    } catch {
      if (import.meta.env.DEV) {
        console.log('ℹ️  No cached team stats found, will use API fallback');
      }
    }
  }
  return teamStatsCache || [];
}

/**
 * Fetch GitHub contributions for a specific user
 * Tries cache first, falls back to API
 * @param username - GitHub username (e.g., 'giuseppi', 'JohnFok119')
 * @returns Contribution calendar data
 */
export async function fetchGitHubContributions(username: string): Promise<GitHubContribution[]> {
  if (!validateGitHubUsername(username)) {
    throw new Error('Invalid GitHub username format');
  }

  // Try cache first
  const cache = await tryLoadCache();
  if (cache.length > 0) {
    const member = cache.find((m) => 
      m.github?.username?.toLowerCase() === username.toLowerCase()
    );
    
    if (member?.github?.contributions) {
      if (import.meta.env.DEV) {
        console.log(`📦 Using cached GitHub data for ${username}`);
      }
      return member.github.contributions;
    }
  }

  // Fallback to API
  try {
    const url = `${API_BASE}/github/contributions?username=${encodeURIComponent(username)}`;
    if (import.meta.env.DEV) {
      console.log(`📡 Fetching GitHub contributions from API: ${url}`);
    }

    const response = await fetch(url);
    const result = await response.json();

    if (!result.success) {
      throw new Error(result.error || 'Failed to fetch GitHub contributions');
    }

    return result.data;
  } catch (error) {
    if (import.meta.env.DEV) {
      console.error(`❌ Error fetching GitHub contributions for ${username}:`, error);
    }
    throw error;
  }
}

/**
 * Fetch commits for a specific repository
 * @param repo - Repository in format 'owner/repo' (e.g., 'jagdteam/Education-Project')
 * @returns Array of filtered and processed commits
 */
export async function fetchRepoCommits(repo: string): Promise<GitHubCommit[]> {
  if (!validateRepoFormat(repo)) {
    throw new Error('Invalid repository format. Expected: owner/repo');
  }

  try {
    const url = `${API_BASE}/github/commits?repo=${encodeURIComponent(repo)}`;
    if (import.meta.env.DEV) {
      console.log(`📡 Fetching commits from: ${url}`);
    }

    const response = await fetch(url);
    const result = await response.json();

    if (!result.success) {
      throw new Error(result.error || 'Failed to fetch repository commits');
    }

    return result.data;
  } catch (error) {
    if (import.meta.env.DEV) {
      console.error(`❌ Error fetching commits for repo ${repo}:`, error);
    }
    throw error;
  }
}
