/**
 * LeetCode API Client
 * Hybrid approach: Tries cached data first, falls back to API if needed
 */

import { validateLeetCodeUsername } from './validators';

/**
 * API Base URL - Points to the backend server
 */
const API_BASE = import.meta.env.VITE_API_BASE_URL || 'https://jagdnotionapiserver.vercel.app/api';

export interface LeetCodeSubmission {
  date: string;
  count: number;
}

export interface LeetCodeStats {
  totalSolved: number;
  easySolved: number;
  mediumSolved: number;
  hardSolved: number;
  recentSubmissions: LeetCodeSubmission[];
}

interface TeamMemberStats {
  name: string;
  github: {
    username: string;
    contributions: Array<{ date: string; count: number }>;
  };
  leetcode: {
    username: string;
    stats: LeetCodeStats;
  } | null;
}

// Cache for static data
let teamStatsCache: TeamMemberStats[] | null = null;
let cacheAttempted = false;

/**
 * Try to load from static cache (generated by sync script)
 */
async function tryLoadCache(): Promise<TeamMemberStats[]> {
  if (!cacheAttempted) {
    cacheAttempted = true;
    try {
      // Use dynamic import with template to prevent Vite static analysis
      const modulePath = `@/data/${'teamStats'}`;
      const module = await import(/* @vite-ignore */ modulePath);
      teamStatsCache = module.teamStats;
      if (import.meta.env.DEV) {
        console.log('✅ Loaded cached team stats from static file');
      }
    } catch {
      if (import.meta.env.DEV) {
        console.log('ℹ️  No cached team stats found, will use API fallback');
      }
    }
  }
  return teamStatsCache || [];
}

/**
 * Fetch LeetCode stats for a specific user
 * Tries cache first, falls back to API
 * @param username - LeetCode username (e.g., 'giuseppi', 'LupusOW')
 * @returns LeetCode statistics and submission history
 */
export async function fetchLeetCodeStats(username: string): Promise<LeetCodeStats | null> {
  if (!username) {
    if (import.meta.env.DEV) {
      console.log('ℹ️  No LeetCode username provided (user may not have account)');
    }
    return null;
  }

  if (!validateLeetCodeUsername(username)) {
    if (import.meta.env.DEV) {
      console.warn('⚠️  Invalid LeetCode username format');
    }
    return null;
  }

  // Try cache first
  const cache = await tryLoadCache();
  if (cache.length > 0) {
    const member = cache.find((m) => 
      m.leetcode?.username?.toLowerCase() === username.toLowerCase()
    );
    
    if (member?.leetcode?.stats) {
      if (import.meta.env.DEV) {
        console.log(`📦 Using cached LeetCode data for ${username}`);
      }
      return member.leetcode.stats;
    }
  }

  // Fallback to API
  try {
    const url = `${API_BASE}/leetcode/stats?username=${encodeURIComponent(username)}`;
    if (import.meta.env.DEV) {
      console.log(`📡 Fetching LeetCode stats from API: ${url}`);
    }

    const response = await fetch(url);
    const result = await response.json();

    if (!result.success) {
      throw new Error(result.error || 'Failed to fetch LeetCode stats');
    }

    return result.data;
  } catch (error) {
    if (import.meta.env.DEV) {
      console.error(`❌ Error fetching LeetCode stats for ${username}:`, error);
    }
    // Return null instead of throwing - LeetCode is optional
    return null;
  }
}
